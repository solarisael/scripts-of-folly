// Generates the WebGL2 leg's GLSL from the same WGSL the vgpu leg runs.
//   bun scripts/build_glsl.js          write src/**/glsl.generated.js
//   bun scripts/build_glsl.js --check  fail when the committed GLSL drifted
// Needs naga-cli 30.0.1 on PATH: cargo install naga-cli --version 30.0.1

import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const check_only = process.argv.includes("--check");

// Each shader: the module and export that hold its WGSL, and the generated
// module the WebGL2 leg imports.
const SHADERS = [
  {
    source: "src/gpu/wgsl.js",
    name: "WGSL_SOURCE",
    output: "src/gpu/glsl.generated.js",
  },
  {
    source: "src/vision/wgsl.js",
    name: "BANNER_WGSL",
    output: "src/vision/glsl.generated.js",
  },
  {
    source: "src/transitions/wgsl.js",
    name: "COVER_WGSL",
    output: "src/transitions/glsl.generated.js",
  },
];

const run_naga = async (input, output, entry_point) => {
  let child;
  try {
    child = Bun.spawn(
      ["naga", input, output, "--profile", "es300", "--entry-point", entry_point],
      { stdout: "pipe", stderr: "pipe" },
    );
  } catch (error) {
    throw new Error(
      "naga is not on PATH: cargo install naga-cli --version 30.0.1",
      { cause: error },
    );
  }
  const [exit_code, stdout, stderr] = await Promise.all([
    child.exited,
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
  ]);
  if (exit_code !== 0) {
    throw new Error(`naga ${entry_point}: ${stderr || stdout}`);
  }
  return (await readFile(output, "utf8")).replace(/\r\n/g, "\n");
};

const translate = async ({ source, name, output }, scratch) => {
  const module = await import(join(root, source));
  const wgsl = module[name];
  if (typeof wgsl !== "string") throw new Error(`${source} has no ${name}.`);
  const input = join(scratch, `${name}.wgsl`);
  await writeFile(input, wgsl);
  const frag = await run_naga(input, join(scratch, `${name}.frag`), "fs_main");
  const vert = await run_naga(input, join(scratch, `${name}.vert`), "vs_main");
  return [
    `// generated by scripts/build_glsl.js from ${name} in ${source}: do not edit.`,
    `export const FRAG = ${JSON.stringify(frag)};`,
    `export const VERT = ${JSON.stringify(vert)};`,
    "",
  ].join("\n");
};

const scratch = await mkdtemp(join(tmpdir(), "folly-glsl-"));
try {
  const stale = [];
  for (const shader of SHADERS) {
    const generated = await translate(shader, scratch);
    const path = join(root, shader.output);
    if (!check_only) {
      await writeFile(path, generated);
      console.log(`wrote ${shader.output}`);
      continue;
    }
    const committed = await readFile(path, "utf8").catch(() => null);
    if (committed?.replace(/\r\n/g, "\n") !== generated) {
      stale.push(shader.output);
    }
  }
  if (stale.length) {
    console.error(
      `GLSL drifted from its WGSL; run bun run glsl:build.\n${stale.join("\n")}`,
    );
    process.exitCode = 1;
  } else if (check_only) {
    console.log(`glsl ok (${SHADERS.length} shaders)`);
  }
} finally {
  await rm(scratch, { recursive: true, force: true });
}
