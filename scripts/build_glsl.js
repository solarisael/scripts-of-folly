// Generates, from the WGSL of each shader, what each leg runs: the prepared
// vgpu shader (wgsl.generated.js, see ./prepared_shader.js) and the naga GLSL
// of the WebGL2 leg (glsl.generated.js).
//   bun scripts/build_glsl.js          write src/**/{wgsl,glsl}.generated.js
//   bun scripts/build_glsl.js --check  fail when a committed file drifted
// Needs naga-cli 30.0.1 on PATH: cargo install naga-cli --version 30.0.1

import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { prepared_module } from "./prepared_shader.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const check_only = process.argv.includes("--check");

// Each shader: the module and export that hold its WGSL, and the generated
// modules the legs import.
const SHADERS = [
  {
    source: "src/gpu/wgsl.js",
    name: "WGSL_SOURCE",
    shader: "src/gpu/wgsl.generated.js",
    glsl: "src/gpu/glsl.generated.js",
  },
  {
    source: "src/vision/wgsl.js",
    name: "BANNER_WGSL",
    shader: "src/vision/wgsl.generated.js",
    glsl: "src/vision/glsl.generated.js",
  },
  {
    source: "src/scene/wgsl.js",
    name: "SCENE_WGSL",
    shader: "src/scene/wgsl.generated.js",
    glsl: "src/scene/glsl.generated.js",
  },
];

const run_naga = async (input, output, entry_point) => {
  let child;
  try {
    child = Bun.spawn(
      [
        "naga",
        input,
        output,
        "--profile",
        "es300",
        "--entry-point",
        entry_point,
      ],
      { stdout: "pipe", stderr: "pipe" },
    );
  } catch (error) {
    throw new Error(
      "naga is not on PATH: cargo install naga-cli --version 30.0.1",
      { cause: error },
    );
  }
  const [exit_code, stdout, stderr] = await Promise.all([
    child.exited,
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
  ]);
  if (exit_code !== 0) {
    throw new Error(`naga ${entry_point}: ${stderr || stdout}`);
  }
  return (await readFile(output, "utf8")).replace(/\r\n/g, "\n");
};

const translate = async ({ source, name }, scratch) => {
  const module = await import(join(root, source));
  const wgsl = module[name];
  if (typeof wgsl !== "string") throw new Error(`${source} has no ${name}.`);
  const input = join(scratch, `${name}.wgsl`);
  await writeFile(input, wgsl);
  const frag = await run_naga(input, join(scratch, `${name}.frag`), "fs_main");
  const vert = await run_naga(input, join(scratch, `${name}.vert`), "vs_main");
  const header = `// generated by scripts/build_glsl.js from ${name} in ${source}: do not edit.`;
  return {
    shader: prepared_module(header, wgsl, source),
    glsl: [
      header,
      `export const FRAG = ${JSON.stringify(frag)};`,
      `export const VERT = ${JSON.stringify(vert)};`,
      "",
    ].join("\n"),
  };
};

const scratch = await mkdtemp(join(tmpdir(), "folly-glsl-"));
try {
  const stale = [];
  for (const shader of SHADERS) {
    const generated = await translate(shader, scratch);
    for (const kind of ["shader", "glsl"]) {
      const path = join(root, shader[kind]);
      if (!check_only) {
        await writeFile(path, generated[kind]);
        console.log(`wrote ${shader[kind]}`);
        continue;
      }
      const committed = await readFile(path, "utf8").catch(() => null);
      if (committed?.replace(/\r\n/g, "\n") !== generated[kind]) {
        stale.push(shader[kind]);
      }
    }
  }
  if (stale.length) {
    console.error(
      `A generated shader drifted from its WGSL; run bun run glsl:build.\n${stale.join("\n")}`,
    );
    process.exitCode = 1;
  } else if (check_only) {
    console.log(`glsl and prepared shaders ok (${SHADERS.length} shaders)`);
  }
} finally {
  await rm(scratch, { recursive: true, force: true });
}
